import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const credentials=JSON.parse(await fs.readFile('backend/provision.local.json','utf8'));
const base='http://127.0.0.1:18881/api/index.php';let cookie='',csrf='';
async function request(action,body,auth=true,token=true){const response=await fetch(`${base}?action=${action}`,{method:body?'POST':'GET',headers:{...(auth?{Cookie:cookie}:{}),...(body?{'Content-Type':'application/json','X-CSRF-Token':token?csrf:'invalid'}:{})},body:body?JSON.stringify(body):undefined});const set=response.headers.getSetCookie();if(auth&&set.length)cookie=set.map(v=>v.split(';')[0]).join('; ');const result=await response.json();if(result.csrf)csrf=result.csrf;return {status:response.status,...result};}
assert.equal((await request('records',undefined,false)).status,401);
assert.equal((await request('session')).authenticated,false);
assert.equal((await request('login',credentials,true,false)).status,403);
assert.equal((await request('login',credentials)).status,200);
assert.equal((await request('session')).authenticated,true);
const baseline=await request('records');assert.ok(baseline.drafts.length>=8);
const id='verification-'+Date.now();
let record={id,kind:'partners',slug:id,status:'draft',updated_at:'',data:{name:'Verification draft',url:'https://example.com'}};
assert.equal((await request('save',{record,publish:false,expected:null})).status,200);
assert.ok(!(await request('public',undefined,false)).published.some(r=>r.id===id));
let saved=(await request('records')).drafts.find(r=>r.id===id);
assert.equal((await request('save',{record:{...saved,status:'published'},publish:true,expected:saved.updated_at})).status,200);
assert.ok((await request('public',undefined,false)).published.some(r=>r.id===id));
assert.equal((await request('save',{record:saved,publish:false,expected:'stale'})).status,409);
saved=(await request('records')).drafts.find(r=>r.id===id);
assert.equal((await request('save',{record:{...saved,status:'draft',data:{...saved.data,name:'Changed draft'}},publish:false,expected:saved.updated_at})).status,200);
assert.equal((await request('public',undefined,false)).published.find(r=>r.id===id).data.name,'Verification draft');
assert.equal((await request('save',{record:{...record,id:id+'-duplicate'},publish:false,expected:null})).status,409);
assert.equal((await request('save',{record:{...record,id:id+'-bad',slug:id+'-bad',data:{name:'Bad',url:'javascript:alert(1)'}},publish:false,expected:null})).status,400);
saved=(await request('records')).drafts.find(r=>r.id===id);
assert.equal((await request('save',{record:{...saved,status:'archived'},publish:false,expected:saved.updated_at})).status,200);
assert.ok(!(await request('public',undefined,false)).published.some(r=>r.id===id));
assert.equal((await request('upload',{content:Buffer.from('<?php echo 1;').toString('base64')})).status,400);
const audit=await request('audit');assert.ok(audit.items.some(r=>r.entity===id));
